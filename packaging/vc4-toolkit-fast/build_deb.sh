#!/bin/sh
# Build vc4-toolkit-fast: the same stack, compiled on this board with speed as
# the only build objective, plus a prewarmed kernel cache and a tuned vc4d.
#
#   packaging/vc4-toolkit-fast/build_deb.sh [VERSION]
#
# It ships the engine under the same soname as vc4infer, so it Conflicts with
# /Replaces vc4infer and vc4-toolkit; `apt install vc4-toolkit-fast` swaps the
# standard stack for this one.
#
# Flags: -O3 -march=native -mtune=native -fno-plt.  LTO is tried for the
# static archive only; the shipped shared library is the non-LTO build.  The
# tests are run for both.  No clock, governor or voltage is touched.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
ver=${1:-1.2.2}
out=$root/dist
stage=$root/build/vc4-toolkit-fast-deb
build=$root/build/vc4-toolkit-fast
triplet=aarch64-linux-gnu
modeldir=$root/infer/packaging/vc4infer/data/models

FASTFLAGS="-O3 -march=native -mtune=native -fno-plt -g -Wall -Wextra -std=gnu11 -fPIC"
JOBS=${JOBS:-2}
# link the client library from this tree, not from a developer checkout
VC4D_DIR=$root/vc4d
export VC4D_DIR

mkdir -p "$build"

# ---------------------------------------------------------------- engine
if [ "${VC4FAST_REUSE:-0}" = 1 ] && [ -f "$build/libvc4infer.so.fast" ]; then
	echo "== reusing $build/libvc4infer.so.fast (VC4FAST_REUSE=1)"
else
	echo "== building libvc4infer with: $FASTFLAGS"
	make -C "$root/infer" clean >/dev/null
	make -C "$root/infer" -j"$JOBS" CFLAGS="$FASTFLAGS" all >/dev/null
	cp "$root/infer/build/libvc4infer.so" "$build/libvc4infer.so.fast"
	cp "$root/infer/build/libvc4infer.a" "$build/libvc4infer.a.fast"
fi

# --------------------------------------------------- tests, non-LTO build
if [ "${VC4FAST_SKIP_TESTS:-0}" != 1 ]; then
	echo "== tests (non-LTO)"
	export VC4INFER_DAEMON=1
	(
		cd "$root/infer/build"
		./test_matmul >/dev/null
		./test_conv 1 >/dev/null
		./test_ew >/dev/null
		./test_onnxops >/dev/null
		./test_grad >/dev/null
		./test_convgrad 1 >/dev/null
		./test_train --opt adam --steps 30 >/dev/null
	)
	echo "   tests passed"
	# keep the fast bench binaries for the documented -O2/-O3 comparison
	cp "$root/infer/build/bench_matmul" "$build/bench_matmul.fast"
	cp "$root/infer/build/test_conv" "$build/test_conv.fast"

	# ------------------------------------------------ tests, LTO archive
	echo "== tests (LTO static archive)"
	make -C "$root/infer" clean >/dev/null
	make -C "$root/infer" -j"$JOBS" AR=gcc-ar CFLAGS="$FASTFLAGS -flto" \
		build/libvc4infer.a build/test_matmul build/test_conv \
		build/test_train >/dev/null
	(
		cd "$root/infer/build"
		./test_matmul >/dev/null
		./test_conv 1 >/dev/null
		./test_train --opt adam --steps 30 >/dev/null
	)
	echo "   LTO archive tests passed"
fi

# ---------------------------------------------------------------- payload
# the prewarmed cache is chmod a-w at the end of a build; make the tree
# removable before rebuilding
chmod -R u+w "$stage" 2>/dev/null || true
rm -rf "$stage"
pkg=$stage/usr/lib/python3/dist-packages
install -d "$stage/DEBIAN" \
	"$stage/usr/bin" \
	"$stage/usr/lib/$triplet" \
	"$stage/usr/lib/vc4infer/kgen" \
	"$stage/usr/lib/vc4infer/kcache" \
	"$stage/usr/share/vc4infer/models" \
	"$stage/usr/share/vc4-toolkit-fast" \
	"$stage/usr/share/doc/vc4-toolkit-fast" \
	"$stage/usr/share/doc/vc4infer" \
	"$stage/usr/share/man/man1" \
	"$pkg/vc4infer/kgen" \
	"$pkg/vc4infer/contrib" \
	"$pkg/vc4infer/ort"

install -m 0755 "$build/libvc4infer.so.fast" "$stage/usr/lib/$triplet/libvc4infer.so.1"
strip --strip-unneeded "$stage/usr/lib/$triplet/libvc4infer.so.1"

# the CLI and the cache-seeding wrapper
install -m 0755 "$root/infer/cli/vc4infer" "$stage/usr/lib/vc4infer/vc4infer-cli"
sed "s/@VERSION@/$ver/" "$here/vc4infer-wrapper.sh" > "$stage/usr/bin/vc4infer"
chmod 0755 "$stage/usr/bin/vc4infer"

# python package (same code as the wheel) and the generator for C clients
install -m 0644 "$root/infer/python/vc4infer"/*.py "$pkg/vc4infer/"
install -m 0644 "$root/infer/python/vc4infer/kgen"/*.py "$pkg/vc4infer/kgen/"
install -m 0644 "$root/infer/python/vc4infer/contrib"/*.py "$pkg/vc4infer/contrib/"
# the ONNX Runtime shim is a subpackage, not a module
install -m 0644 "$root/infer/python/vc4infer/ort"/*.py "$pkg/vc4infer/ort/" 2>/dev/null || true
for f in kgen.py kops.py qenc.py gen.py vpmwords.py; do
	install -m 0644 "$root/infer/tools/$f" "$stage/usr/lib/vc4infer/kgen/$f"
done

# bundled models (same set as vc4infer)
install -m 0644 "$modeldir"/* "$stage/usr/share/vc4infer/models/"

# ------------------------------------------------------- prewarm kcache
# A seed cache generated by the same kgen.py is byte-valid (the stamps hash
# the generator content, not the path); the selftest below fills any gap and
# proves the seeded set is complete.  Used to rebuild the package after a
# board reboot without re-running 10 minutes of JIT.
if [ -n "${VC4FAST_SEED_CACHE:-}" ] && [ -d "$VC4FAST_SEED_CACHE" ]; then
	echo "== seeding the kernel cache from $VC4FAST_SEED_CACHE"
	cp -a "$VC4FAST_SEED_CACHE"/. "$stage/usr/lib/vc4infer/kcache"/ 2>/dev/null || true
fi

echo "== prewarming the kernel cache (bundled models)"
if [ "${VC4FAST_PREWARM_RUN:-1}" = 1 ]; then
	# Running the bundled models through the engine both JITs anything the
	# seed is missing and proves the cache is complete.  It needs a live
	# GPU; on a shared board another job can wedge V3D, so a rebuild from a
	# previously validated seed can skip it with VC4FAST_PREWARM_RUN=0.
	env VC4INFER_LIB="$build/libvc4infer.so.fast" \
		VC4INFER_KGEN="$stage/usr/lib/vc4infer/kgen/kgen.py" \
		VC4INFER_CACHE="$stage/usr/lib/vc4infer/kcache" \
		VC4INFER_DAEMON=1 \
		PYTHONPATH="$root/infer/python" \
		python3 "$root/infer/cli/vc4infer" selftest \
		--models "$stage/usr/share/vc4infer/models" >/dev/null
else
	echo "   skipped (VC4FAST_PREWARM_RUN=0): using the seeded, previously"
	echo "   validated set"
fi

blobs=$(find "$stage/usr/lib/vc4infer/kcache" -name '*.bin' | wc -l)
[ "$blobs" -gt 0 ] || { echo "prewarm produced no blobs" >&2; exit 1; }

cat > "$stage/usr/lib/vc4infer/kcache/MANIFEST" <<EOF
vc4-toolkit-fast $ver prewarmed kernel cache
generated:  $(date -u +%Y-%m-%dT%H:%M:%SZ)
board:      $(uname -m), $(tr -d '\0' < /proc/device-tree/model 2>/dev/null || echo "Raspberry Pi")
blobs:      $blobs
generator:  sha256 $(sha256sum "$stage/usr/lib/vc4infer/kgen/kgen.py" | cut -d' ' -f1)
abi:        vc4infer-kernel-abi-2
models:     modelA modelB modelC yolov8n_160
EOF

# read-only: the engine's stamps travel with the blobs
find "$stage/usr/lib/vc4infer/kcache" -type f -exec chmod 0444 {} +
find "$stage/usr/lib/vc4infer/kcache" -type d -exec chmod 0555 {} +

# ------------------------------------------------------ daemon drop-in
install -m 0644 "$here/10-fast.conf" \
	"$stage/usr/share/vc4-toolkit-fast/10-fast.conf"
install -m 0644 "$here/vc4d-fast.default" \
	"$stage/usr/share/vc4-toolkit-fast/vc4d-fast.default"
install -m 0755 "$here/vc4fast" "$stage/usr/bin/vc4fast"

# ---------------------------------------------------------------- docs
install -m 0644 "$here/README.md" "$stage/usr/share/doc/vc4-toolkit-fast/README.md"
install -m 0644 "$here/vc4fast.1" \
	"$stage/usr/share/man/man1/vc4fast.1"
gzip -9n "$stage/usr/share/man/man1/vc4fast.1"
chmod 0644 "$stage/usr/share/man/man1/vc4fast.1.gz"

install -m 0644 "$root/docs/VC4INFER.md" "$stage/usr/share/doc/vc4infer/README.md"
install -m 0644 "$root/docs/PYTHON-API.md" \
	"$stage/usr/share/doc/vc4infer/PYTHON-API.md"

# ---------------------------------------------------------------- control
PKG=vc4-toolkit-fast
VER=$ver
ARCH=arm64
DEPENDS="vc4d (>= 1.2.1), vc4infer-dev (>= 1.2.2), vc4-query (>= 1.0.0), vc4-smi (>= 1.0.0), vc4train (>= 1.0.0), vc4top (>= 1.0.5), vc4top-dkms (>= 1.0.5), python3 (>= 3.11), python3-numpy, python3-onnx (>= 1.14), python3-pil, libc6 (>= 2.38)"
SECTION=metapackages
SHORT="VideoCore IV toolkit built from source with -O3 -march=native (speed path)"
LONG="The vc4-toolkit stack rebuilt on the target board with speed as the only
objective:
 .
  * the engine compiled with -O3 -march=native -mtune=native -fno-plt (the
    standard package is -O2); the static archive is also built with LTO and
    the tests are run against it
  * /usr/lib/vc4infer/kcache prewarmed at package build time with every kernel
    blob the bundled models need, stamped and read-only, so a first run does
    not JIT
  * a vc4d drop-in with --arena-mb 150 and --max-timeout-ms 60000 (the 320x320
    recipe), toggled by vc4fast on|off|status
 .
 No clock, governor or voltage is changed: the board stays at stock core
 400 MHz / V3D 300 MHz.  See /usr/share/doc/vc4-toolkit-fast/README.md for the
 measured difference against the -O2 package."
EXTRA="Provides: vc4-toolkit
Conflicts: vc4-toolkit, vc4infer
Replaces: vc4-toolkit, vc4infer"
CONFFILES=""

. "$here/../common.sh"
deb_finish "$stage" "$out"
