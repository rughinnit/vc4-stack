#!/usr/bin/env python3
"""Publish docs/ to the GitHub wiki as a generated mirror.

    tools/wiki_sync.py [--dry-run]

The repository is the source: every page carries the commit it was generated
from and says to edit the repository instead.  Links to other synced pages are
rewritten from `NAME.md` to the wiki page `NAME`; everything else is left as
written.  Home is regenerated as the index.

The wiki repository is cloned under TMPDIR (never /tmp), so the same clone is
reused between runs.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIKI_URL = "git@github.com:rughinnit/vc4-stack.wiki.git"
INDEX = "Home"


def run(args, cwd=None, check=True):
    return subprocess.run(args, cwd=cwd, check=check,
                          capture_output=True, text=True)


def sha():
    return run(["git", "-C", REPO, "rev-parse", "--short", "HEAD"]).stdout.strip()


def pages():
    """Repo path -> wiki page name."""
    out = {"README.md": "Overview"}
    docs = os.path.join(REPO, "docs")
    for name in sorted(os.listdir(docs)):
        if name.endswith(".md") and name != "README.md":
            out["docs/" + name] = name[:-3]
    out["docs/README.md"] = "Documentation-Index"
    return out


def rewrite_links(text, names):
    def repl(m):
        target, anchor = m.group(1), m.group(2) or ""
        if "://" in target or target.startswith("#"):
            return m.group(0)
        base = os.path.basename(target)
        if base.endswith(".md") and base[:-3] in names:
            return "](%s%s)" % (base[:-3], anchor)
        return m.group(0)
    return re.sub(r"\]\(([^)\s]+?)(#[^)\s]*)?\)", repl, text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    tmp = os.environ.get("TMPDIR", os.path.join(os.path.expanduser("~"), "scratch/tmp"))
    work = os.path.join(tmp, "vc4-wiki")
    if os.path.isdir(os.path.join(work, ".git")):
        # the mirror is generated; discard anything left from an interrupted run
        run(["git", "-C", work, "reset", "-q", "--hard"])
        run(["git", "-C", work, "clean", "-qfd"])
        run(["git", "-C", work, "pull", "-q", "--rebase"])
    else:
        if os.path.isdir(work):
            shutil.rmtree(work)
        run(["git", "clone", "-q", WIKI_URL, work])

    mapping = pages()
    names = set(mapping.values())
    commit = sha()
    written = 0
    for path, page in mapping.items():
        src = os.path.join(REPO, path)
        if not os.path.exists(src):
            continue
        body = open(src, encoding="utf-8").read()
        body = rewrite_links(body, names)
        header = (
            "<!-- Generated from %s at %s. Edit the repository, not this page. -->\n\n"
            "> Generated from [`%s`](https://github.com/rughinnit/vc4-stack/blob/main/%s) "
            "at `%s`. Edit the repository, not this page.\n\n"
            % (path, commit, path, path, commit))
        with open(os.path.join(work, page + ".md"), "w", encoding="utf-8") as fh:
            fh.write(header + body)
        written += 1

    lines = [
        "<!-- Generated by tools/wiki_sync.py. Edit the repository, not this page. -->",
        "",
        "# VC4 stack wiki",
        "",
        "Generated from [`rughinnit/vc4-stack`](https://github.com/rughinnit/vc4-stack) "
        "at `%s`." % commit,
        "",
        "| page | source |",
        "|---|---|",
    ]
    for path, page in sorted(mapping.items(), key=lambda kv: kv[1]):
        lines.append("| [%s](%s) | `%s` |" % (page, page, path))
    lines += ["", "The repository is the source of truth; this wiki is a mirror."]
    with open(os.path.join(work, INDEX + ".md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    written += 1

    run(["git", "-C", work, "add", "-A"])
    diff = run(["git", "-C", work, "status", "--porcelain"]).stdout.strip()
    print("pages written:", written, "| changed:", len(diff.splitlines()))
    if not diff:
        return 0
    if args.dry_run:
        print(diff)
        return 0
    run(["git", "-C", work, "commit", "-q", "-m",
         "docs: mirror the repository at %s" % commit])
    run(["git", "-C", work, "push", "-q", "origin", "HEAD"])
    print("pushed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
